// test RF channel data APIs ---------------------------------------------------
static void test_sdr_rcv_rfch_data_api(void)
{
    sdr_rcv_t *rcv = new_rcv_empty(SDR_FMT_INT8, 1000.0, "");
    double stat[8], hist1[256], hist2[256];
    float psd[16];
    int val[256];
    
    for (int i = 0; i < rcv->buff[0]->N; i++) {
        rcv->buff[0]->data[i] = SDR_CPX8((int8_t)(i % 5 - 2),
            (int8_t)(2 - i % 5));
    }
    rcv->state = 1;
    rcv->dev = SDR_DEV_FILE;
    rcv->ix = 20;
    rcv->stats.std = 1.25;
    
    TEST_ASSERT_EQ_INT(1, sdr_rcv_rfch_stat(rcv, 1, stat));
    TEST_ASSERT_NEAR(SDR_DEV_FILE, stat[0], 1e-12);
    TEST_ASSERT_NEAR(SDR_FMT_INT8, stat[1], 1e-12);
    TEST_ASSERT_NEAR(1000.0, stat[2], 1e-12);
    TEST_ASSERT_NEAR(1.25, stat[6], 1e-12);
    TEST_ASSERT_EQ_INT(0, sdr_rcv_rfch_stat(rcv, 2, stat));
    TEST_ASSERT_EQ_INT(16, sdr_rcv_rfch_psd(rcv, 1, 0.016, 16, psd));
    TEST_ASSERT_TRUE(sdr_rcv_rfch_hist(rcv, 1, 0.010, val, hist1, hist2) > 0);
    TEST_ASSERT_EQ_INT(0, sdr_rcv_rfch_psd(rcv, 1, 0.001, 16, psd));
    
    rcv->state = 0;
    sdr_rcv_free(rcv);
    cleanup_files();
}

