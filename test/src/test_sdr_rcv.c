// test file contains a string -------------------------------------------------
static int file_contains(const char *file, const char *str)
{
    FILE *fp = fopen(file, "rb");
    char buff[4096] = "";

    if (!fp) return 0;
    size_t n = fread(buff, 1, sizeof(buff) - 1, fp);
    buff[n] = '\0';
    fclose(fp);
    return strstr(buff, str) != NULL;
}

// remove files generated by these tests ---------------------------------------
static void cleanup_files(void)
{
    remove(NAVDATA_FILE);
    remove(TRACE_FILE);
}

// create receiver without tracking channels -----------------------------------
